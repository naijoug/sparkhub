/** 审美配比：真实产品 70% · 视觉案例 20% · 跨界实验 10%；工具/规范不计入配比。 */
export type SourceDiet = "product" | "visual" | "frontier" | "toolkit";

/** 巡航频率：每日漫游扫描时的建议回访节律。 */
export type ScanCadence = "daily" | "weekly" | "monthly" | "on-demand";

export type SourcePlatform = "iOS" | "Android" | "Web" | "Email" | "Print";

export interface InspirationSource {
  id: string;
  name: string;
  url: string;
  sections: SourceSectionId[];
  /** 板块内的子分组，例如「偏实用」「官方设计系统」「图标」。 */
  group?: string;
  summary: string;
  focus: string[];
  platforms?: SourcePlatform[];
  diet: SourceDiet;
  cadence: ScanCadence;
  /** 核心 12 站：建议优先收藏与巡航。 */
  core?: boolean;
  /** 扫描方式：默认可直接抓取；browser 表示需真实浏览器访问。 */
  access?: "browser";
  /** 素材可商用前须单独核查授权。 */
  licenseCheck?: boolean;
  caveat?: string;
}

