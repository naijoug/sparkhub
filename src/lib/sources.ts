/** 按巡航频率分组的扫描清单（不含按需查阅的工具类站点）。 */
export function getScanPlan() {
  const plan: Record<Exclude<ScanCadence, "on-demand">, InspirationSource[]> = {
    daily: [],
    weekly: [],
    monthly: [],
  };
  for (const source of inspirationSources) {
    if (source.cadence !== "on-demand") plan[source.cadence].push(source);
  }
  return plan;
}

export function matchesSourceQuery(source: InspirationSource, query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  return (
    source.name.toLowerCase().includes(q) ||
    source.summary.toLowerCase().includes(q) ||
    source.url.toLowerCase().includes(q) ||
    (source.group?.toLowerCase().includes(q) ?? false) ||
    source.focus.some((f) => f.toLowerCase().includes(q)) ||
    (source.platforms?.some((p) => p.toLowerCase().includes(q)) ?? false)
  );
}
